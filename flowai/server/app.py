"""FastAPI REST and SSE streaming API server.

The server drives agents that can touch the machine, so it is locked down:

- Every route except /health needs `Authorization: Bearer <token>`. The
  token comes from FLOWAI_SERVER_TOKEN or is generated by `flowai serve`.
- Bound to localhost, it only answers requests whose Host header is local,
  which stops DNS-rebinding attacks from a web page in your browser.
- Shell and python tools are refused unless the server was started with
  --allow-shell, and every tool call goes through the Shield.
- Error messages are redacted before they are returned.
"""

from __future__ import annotations

import hmac
import json
from typing import Any

from pydantic import BaseModel

try:
    from fastapi import FastAPI, HTTPException, Request
    from fastapi.middleware.cors import CORSMiddleware
    from fastapi.responses import JSONResponse, StreamingResponse
except ImportError:
    FastAPI = None

from flowai import __version__
from flowai.agents.standard import Agent
from flowai.config.settings import Settings
from flowai.errors import FlowAIError
from flowai.providers.registry import ProviderRegistry, get_provider
from flowai.security.secrets import redact
from flowai.security.shield import Shield
from flowai.tools.builtin import default_system_prompt, default_toolset
from flowai.tools.registry import ToolRegistry

LOCAL_HOSTS = {"localhost", "127.0.0.1", "[::1]", "::1"}
PUBLIC_PATHS = {"/health"}


class ChatRequest(BaseModel):
    message: str
    agent: str = "default"
    provider: str | None = None
    model: str | None = None
    stream: bool = False


class AgentCreateRequest(BaseModel):
    name: str
    provider: str = "openai"
    model: str | None = None
    system_prompt: str = "You are a helpful AI assistant."


def create_app(
    settings: Settings | None = None,
    token: str | None = None,
    allow_shell: bool = False,
    local_only: bool = True,
) -> Any:
    if FastAPI is None:
        raise ImportError("FastAPI is required to run the server. Install with: pip install 'flowai-cli[server]'")

    cfg = settings or Settings.load()
    app = FastAPI(title="FlowAI Agent Harness API", version=__version__)

    # Agents here can run tools, so only local pages may call the API from a browser.
    app.add_middleware(
        CORSMiddleware,
        allow_origin_regex=r"^http://(localhost|127\.0\.0\.1)(:\d+)?$",
        allow_methods=["GET", "POST"],
        allow_headers=["Authorization", "Content-Type"],
    )

    @app.middleware("http")
    async def guard(request: Request, call_next):
        if local_only:
            host = (request.headers.get("host") or "").rsplit(":", 1)[0].lower()
            if host not in LOCAL_HOSTS:
                return JSONResponse({"detail": "Host not allowed."}, status_code=403)
        if request.method != "OPTIONS" and request.url.path not in PUBLIC_PATHS:
            if not token:
                return JSONResponse({"detail": "Server started without a token; refusing all requests."}, 503)
            supplied = request.headers.get("authorization", "")
            expected = f"Bearer {token}"
            if not hmac.compare_digest(supplied.encode(), expected.encode()):
                return JSONResponse({"detail": "Missing or wrong bearer token."}, status_code=401)
        return await call_next(request)

    async def server_approver(tool_name: str, arguments: dict, risk=None) -> bool:
        # Nobody is at a terminal to confirm, so gated tools need --allow-shell,
        # and calls that touch secrets are never run on behalf of an HTTP client.
        if risk is not None and risk.level == "critical":
            return False
        return allow_shell

    tool_registry = ToolRegistry(default_toolset(), approver=server_approver, shield=Shield())

    def make_agent(name: str, provider: str, model: str | None, system_prompt: str | None = None) -> Agent:
        try:
            ProviderRegistry.get(provider)
        except ValueError as exc:
            raise HTTPException(status_code=400, detail=str(exc)) from exc
        model = model or (cfg.model if provider == cfg.provider else None)
        instance = get_provider(provider, model=model, **cfg.provider_options(provider))
        return Agent(
            name=name,
            provider=instance,
            model=instance.model,
            system_prompt=system_prompt or default_system_prompt(),
            tools=tool_registry,
        )

    agents_store: dict[str, Agent] = {"default": make_agent("DefaultAgent", cfg.provider, cfg.model)}

    @app.get("/health")
    async def health():
        return {"status": "ok", "version": __version__}

    @app.get("/tools")
    async def list_tools():
        return {"tools": tool_registry.get_schemas(format="openai")}

    @app.get("/agents")
    async def list_agents():
        return {
            "agents": [
                {
                    "name": a.name,
                    "model": a.model,
                    "provider": a.provider.provider_name,
                    "system_prompt": a.system_prompt,
                }
                for a in agents_store.values()
            ]
        }

    @app.post("/agents")
    async def create_agent(req: AgentCreateRequest):
        agents_store[req.name] = make_agent(req.name, req.provider, req.model, req.system_prompt)
        return {"message": f"Agent '{req.name}' created successfully."}

    @app.post("/chat")
    async def chat(req: ChatRequest):
        agent = agents_store.get(req.agent)
        if not agent:
            agent = make_agent(req.agent, req.provider or cfg.provider, req.model)
            agents_store[req.agent] = agent

        if not req.stream:
            try:
                reply = await agent.run(req.message)
            except FlowAIError as exc:
                raise HTTPException(status_code=502, detail=redact(str(exc))) from exc
            return {"reply": redact(reply), "agent": req.agent}

        async def sse_generator():
            try:
                async for chunk in agent.stream(req.message):
                    if chunk.text_delta:
                        yield f"data: {json.dumps({'token': redact(chunk.text_delta)})}\n\n"
            except FlowAIError as exc:
                yield f"data: {json.dumps({'error': redact(str(exc))})}\n\n"
            yield f"data: {json.dumps({'done': True})}\n\n"

        return StreamingResponse(sse_generator(), media_type="text/event-stream")

    return app
